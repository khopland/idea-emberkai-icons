package com.github.khopland.symbols.generated

import com.github.khopland.symbols.core.IconRuleCategory
import com.github.khopland.symbols.settings.EmberkaiIconsSettings
import com.github.khopland.symbols.settings.isEnabled
import com.github.khopland.symbols.tooltips.SemanticTooltipDecorator
import com.intellij.ide.projectView.PresentationData
import com.intellij.ide.projectView.ProjectViewNode
import com.intellij.ide.projectView.ProjectViewNodeDecorator
import com.intellij.openapi.fileEditor.FileDocumentManager
import com.intellij.openapi.project.Project
import com.intellij.openapi.roots.GeneratedSourcesFilter
import com.intellij.openapi.util.Key
import com.intellij.openapi.vfs.VirtualFile
import java.io.IOException
import java.util.Locale

/**
 * Recognizes generated files: a header that says so, such as `DO NOT EDIT` or `This file is
 * generated by jOOQ`, or a source root that IntelliJ marks as generated. Only the first
 * [HEADER_LENGTH] characters are read, cached per modification stamp, including unsaved edits.
 */
internal object GeneratedFiles {
    const val HEADER_LENGTH = 4096

    /** Phrases generators write. Matching is case-sensitive only where everyday prose would clash. */
    private val MARKERS = listOf(
        Regex("""DO NOT EDIT"""),
        // Lowercase only: `@Generated` annotations also mark hand-written code to exclude it from coverage.
        Regex("""@generated\b"""),
        Regex("""\bauto[- ]?generated\b""", RegexOption.IGNORE_CASE),
        Regex("""\bautomatically generated\b""", RegexOption.IGNORE_CASE),
        Regex("""\bthis (?:file|class|code|source) (?:is|was|has been) (?:auto[- ]?)?generated\b""", RegexOption.IGNORE_CASE),
        Regex("""\bcode generated by\b""", RegexOption.IGNORE_CASE),
        Regex("""\bgenerated by the protocol buffer compiler\b""", RegexOption.IGNORE_CASE),
        Regex("""\bdo not (?:edit|modify) (?:this file|manually|by hand)\b""", RegexOption.IGNORE_CASE),
    )

    /** Prose files quote these phrases rather than carry them. */
    private val PROSE_EXTENSIONS = setOf("md", "markdown", "txt", "rst", "adoc", "asciidoc")

    private data class Header(val stamp: Long, val fromDocument: Boolean, val marker: String?)

    private val HEADER = Key.create<Header>("emberkai.generatedHeader")

    /** Why [file] is generated, such as `header says "DO NOT EDIT"`, or null when it looks hand-written. */
    fun reason(file: VirtualFile, project: Project): String? {
        if (file.isDirectory || !file.isValid) return null
        headerMarker(file)?.let { return "header says \"$it\"" }
        val inGeneratedRoot = GeneratedSourcesFilter.EP_NAME.extensionList
            .any { it !is EmberkaiGeneratedSourcesFilter && it.isGeneratedSource(file, project) }
        return if (inGeneratedRoot) "in a generated source root" else null
    }

    /** The phrase in [file]'s header that marks it as generated, as written. */
    fun headerMarker(file: VirtualFile): String? {
        if (file.isDirectory || !file.isValid || file.fileType.isBinary) return null
        if (file.extension?.lowercase(Locale.ROOT) in PROSE_EXTENSIONS) return null
        val document = FileDocumentManager.getInstance().getCachedDocument(file)
        val stamp = document?.modificationStamp ?: file.modificationStamp
        file.getUserData(HEADER)?.takeIf { it.stamp == stamp && it.fromDocument == (document != null) }?.let { return it.marker }
        val header = try {
            document?.immutableCharSequence?.let { it.subSequence(0, minOf(it.length, HEADER_LENGTH)).toString() }
                ?: file.inputStream.use { String(it.readNBytes(HEADER_LENGTH), file.charset) }
        } catch (_: IOException) {
            return null
        }
        val marker = find(header)
        file.putUserData(HEADER, Header(stamp, document != null, marker))
        return marker
    }

    fun find(header: String): String? = MARKERS.firstNotNullOfOrNull { it.find(header)?.value }
}

/**
 * Tells IntelliJ that header-marked files are generated, as it already knows for generated source
 * roots. The IDE then warns when such a file is edited, and groups usages in it as generated code.
 */
class EmberkaiGeneratedSourcesFilter : GeneratedSourcesFilter() {
    override fun isGeneratedSource(file: VirtualFile, project: Project): Boolean =
        enabled() && GeneratedFiles.headerMarker(file) != null

    override fun getNotificationText(file: VirtualFile, project: Project): String? {
        if (!enabled()) return null
        val marker = GeneratedFiles.headerMarker(file) ?: return null
        return "This file's header says \"$marker\": it is generated, and edits will be lost when it is generated again."
    }

    private fun enabled() = EmberkaiIconsSettings.getInstance().isEnabled(IconRuleCategory.GENERATED_FILES)
}

/** Adds a grey "generated" hint after generated files in the Project view, with the reason in the tooltip. */
class GeneratedFileDecorator : ProjectViewNodeDecorator {
    override fun decorate(node: ProjectViewNode<*>, data: PresentationData) {
        if (!EmberkaiIconsSettings.getInstance().isEnabled(IconRuleCategory.GENERATED_FILES)) return
        val project = node.project?.takeUnless { it.isDisposed } ?: return
        val file = node.virtualFile?.takeIf { !it.isDirectory } ?: return
        val reason = GeneratedFiles.reason(file, project) ?: return
        if (data.locationString.isNullOrEmpty()) data.locationString = "generated"
        data.tooltip = SemanticTooltipDecorator.appendTooltip(data.tooltip, "Generated: $reason")
    }
}
