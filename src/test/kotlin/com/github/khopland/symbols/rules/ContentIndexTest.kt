package com.github.khopland.symbols.rules

import com.github.khopland.symbols.IconProviderTestCase
import com.github.khopland.symbols.badges.KubernetesSecrets
import com.github.khopland.symbols.core.StructuredFileKind
import com.github.khopland.symbols.generated.GeneratedFiles
import com.intellij.openapi.application.ApplicationManager
import com.intellij.openapi.application.runReadAction
import com.intellij.openapi.command.WriteCommandAction
import com.intellij.openapi.fileEditor.FileDocumentManager
import com.intellij.openapi.vfs.VirtualFile
import com.intellij.util.indexing.FileBasedIndex
import java.util.concurrent.TimeUnit

internal class ContentIndexTest : IconProviderTestCase() {
    fun testIndexStoresWhatTheReadersFind() {
        val deployment = file("deploy/app.yaml", "apiVersion: apps/v1\nkind: Deployment\nmetadata: {name: app}")
        assertEquals(mapOf("indexed" to "", "kind:KUBERNETES" to "deployment"), indexed(deployment))

        val openApi = file("api.yaml", "openapi: 3.1.0\ninfo: {title: API}")
        assertEquals(mapOf("indexed" to "", "kind:OPEN_API" to ""), indexed(openApi))

        val sops = file(".env.production", "TOKEN=ENC[AES256_GCM,data:abc,type:str]\nsops_mac=ENC[AES256_GCM,data:def,type:str]\n")
        assertEquals(mapOf("indexed" to "", "sops" to ""), indexed(sops))

        val generated = file("Client.ts", "// Code generated by openapi-generator. DO NOT EDIT.\nexport {}")
        assertEquals(mapOf("indexed" to "", "generated" to "DO NOT EDIT"), indexed(generated))

        val prose = file("README.md", "This file is generated by the build. DO NOT EDIT.")
        assertEquals("Prose quotes markers rather than carrying them", mapOf("indexed" to ""), indexed(prose))
    }

    fun testBackgroundCallersReadTheIndexAndTheEdtReadsTheFile() {
        val secret = file("secret.yaml", "apiVersion: v1\nkind: Secret\nmetadata: {name: db}\nstringData: {password: hunter2}")
        assertNull("The EDT never waits for indexing", ContentIndex.facts(secret, project))
        assertNull("Without a project there is nothing to query", inBackground { ContentIndex.facts(secret, null) })

        val facts = inBackground { ContentIndex.facts(secret, project) }
        assertNotNull(facts)
        assertEquals(StructuredFileKind.Metadata(StructuredFileKind.KUBERNETES, "secret"), facts!!.structured)
        assertFalse(facts.sopsEncrypted)
        assertNull(facts.generatedMarker)

        // Both paths agree.
        assertEquals(StructuredFileKind.of(secret), inBackground { StructuredFileKind.of(secret, project) })
        assertEquals(KubernetesSecrets.plaintext(secret), inBackground { KubernetesSecrets.plaintext(secret, project) })
        val generated = file("Api.java", "/* DO NOT EDIT */\nclass Api {}")
        assertEquals(GeneratedFiles.headerMarker(generated), inBackground { GeneratedFiles.headerMarker(generated, project) })
    }

    fun testUnsavedEditsAreReadFromTheDocument() {
        val manifest = file("service.yaml", "apiVersion: v1\nkind: Service\nmetadata: {name: api}")
        val document = FileDocumentManager.getInstance().getDocument(manifest)!!
        WriteCommandAction.runWriteCommandAction(project) {
            document.setText("apiVersion: v1\nkind: ConfigMap\nmetadata: {name: api}")
        }
        assertNull("The saved file no longer matches", inBackground { ContentIndex.facts(manifest, project) })
        assertEquals("configmap", inBackground { StructuredFileKind.kubernetesResource(manifest, project) })
    }

    private fun file(path: String, text: String): VirtualFile = myFixture.addFileToProject(path, text).virtualFile

    private fun indexed(file: VirtualFile): Map<String, String> =
        FileBasedIndex.getInstance().getFileData(ContentIndex.NAME, file, project)

    private fun <T> inBackground(query: () -> T): T =
        ApplicationManager.getApplication().executeOnPooledThread<T> { runReadAction(query) }.get(30, TimeUnit.SECONDS)
}
