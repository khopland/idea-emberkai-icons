import org.jetbrains.jps.model.java.JavaSourceRootType
import org.jetbrains.jps.model.java.JpsJavaExtensionService

internal class GeneratedFilesTest : IconProviderTestCase() {
    private lateinit var settings: EmberkaiIconsSettings
    private var savedState: EmberkaiIconsSettings.State? = null

    override fun setUp() {
        super.setUp()
        settings = EmberkaiIconsSettings.getInstance()
        savedState = settings.state
    }

    override fun tearDown() {
        try {
            savedState?.let(settings::loadState)
        } finally {
            super.tearDown()
        }
    }

    fun testHeadersThatGeneratorsWrite() {
        val generated = mapOf(
            "// Generated by the protocol buffer compiler.  DO NOT EDIT!" to "DO NOT EDIT",
            "// Code generated by sqlc. DO NOT EDIT." to "DO NOT EDIT",
            "/*\n * This file is generated by jOOQ.\n */" to "This file is generated",
            " * NOTE: This class is auto generated by OpenAPI Generator (https://openapi-generator.tech)." to "auto generated",
            "# This file was autogenerated by uv" to "autogenerated",
            "// @generated by protoc-gen-es v1.0" to "@generated",
            "<!-- Automatically generated, do not modify by hand -->" to "Automatically generated",
            "// Do not edit this file; run ./gradlew generate instead" to "Do not edit this file",
        )
        for ((header, marker) in generated) assertEquals(header, marker, GeneratedFiles.find(header))

        for (header in listOf(
            "@Generated\npublic class Handwritten {}",
            "// Keep in sync with the generator, but edit freely",
            "# Generated by Django 4.2 on 2026-01-01",
            "// do not edit without telling the payments team",
            "public class Plain {}",
            // Eclipse's method and catch templates leave these in hand-written code.
            "package demo;\n\npublic class Service {\n    public void run() {\n        // TODO Auto-generated method stub\n    }\n}",
            "package demo;\n\n@Entity\npublic class Order {\n    /** Primary key, automatically generated. */\n    @Id @GeneratedValue\n    Long id;\n}",
            "export const id = 1 // auto-generated by the database",
        )) {
            assertNull(header, GeneratedFiles.find(header))
        }
    }

    fun testAutoGeneratedCountsOnlyInTheOpeningComments() {
        for ((header, marker) in mapOf(
            "<?xml version=\"1.0\"?>\n<!--\n  Automatically generated from schema.xsd\n-->\n<root/>" to "Automatically generated",
            "#!/usr/bin/env python\n# -*- coding: utf-8 -*-\n\n# auto-generated by tool\nimport os" to "auto-generated",
            "\"\"\"\nAuto-generated client.\n\"\"\"\nimport os" to "Auto-generated",
            "/*\n Auto-generated by apollo\n*/\nexport {}" to "Auto-generated",
        )) {
            assertEquals(header, marker, GeneratedFiles.find(header))
        }
        assertEquals("", GeneratedFiles.leadingComments("package demo;\n// auto-generated"))
        assertEquals("// header\n\n/* a\n   b */", GeneratedFiles.leadingComments("// header\n\n/* a\n   b */\nval x = 1"))
    }

    fun testMarkedFilesAreGeneratedForTheIde() {
        val file = myFixture.addFileToProject("api/Client.ts", "// Code generated by openapi. DO NOT EDIT.\nexport {}").virtualFile
        val plain = myFixture.addFileToProject("api/index.ts", "export * from './Client'").virtualFile
        val notes = myFixture.addFileToProject("NOTES.md", "Files marked DO NOT EDIT are generated.").virtualFile

        assertTrue(GeneratedSourcesFilter.EP_NAME.extensionList.any { it is EmberkaiGeneratedSourcesFilter })
        assertTrue(GeneratedSourcesFilter.isGeneratedSourceByAnyFilter(file, project))
        assertFalse(GeneratedSourcesFilter.isGeneratedSourceByAnyFilter(plain, project))
        assertFalse("Prose quotes the phrase", GeneratedSourcesFilter.isGeneratedSourceByAnyFilter(notes, project))
        assertEquals(
            "This file's header says \"DO NOT EDIT\": it is generated, and edits will be lost when it is generated again.",
            EmberkaiGeneratedSourcesFilter().getNotificationText(file, project),
        )

        settings.setEnabled(IconRuleCategory.GENERATED_FILES, false)
        assertFalse(GeneratedSourcesFilter.isGeneratedSourceByAnyFilter(file, project))
    }

    fun testOnlyTheHeaderIsRead() {
        val late = "x".repeat(GeneratedFiles.HEADER_LENGTH) + "\n// DO NOT EDIT"
        assertNull(GeneratedFiles.headerMarker(myFixture.addFileToProject("late.ts", late).virtualFile))
    }

    fun testUnsavedEditsAreFollowed() {
        val file = myFixture.addFileToProject("schema.ts", "export {}")
        assertNull(GeneratedFiles.headerMarker(file.virtualFile))
        edit(file, "// DO NOT EDIT\nexport {}")
        assertEquals("DO NOT EDIT", GeneratedFiles.headerMarker(file.virtualFile))
    }

    fun testProjectViewHintAndTooltip() {
        val generated = myFixture.addFileToProject("gen/Orders.ts", "// DO NOT EDIT\nexport {}")
        val plain = myFixture.addFileToProject("src/Orders.ts", "export {}")

        val data = decorate(generated)
        assertEquals("generated", data.locationString)
        assertEquals("Generated: header says \"DO NOT EDIT\"", data.tooltip)
        assertNull(decorate(plain).locationString)

        val existing = PresentationData().apply { locationString = "module-a" }
        GeneratedFileDecorator().decorate(PsiFileNode(project, generated, ViewSettings.DEFAULT), existing)
        assertEquals("An existing location stays", "module-a", existing.locationString)

        settings.setEnabled(IconRuleCategory.GENERATED_FILES, false)
        assertNull(decorate(generated).locationString)
    }

    fun testGeneratedSourceRootsAndScope() {
        val root = myFixture.tempDirFixture.findOrCreateDir("build/generated/sources/openapi")
        PsiTestUtil.addSourceRoot(
            module,
            root,
            JavaSourceRootType.SOURCE,
            JpsJavaExtensionService.getInstance().createSourceRootProperties("", true),
        )
        val inRoot = myFixture.addFileToProject("build/generated/sources/openapi/Order.kt", "class Order").virtualFile
        val marked = myFixture.addFileToProject("web/api.ts", "/* auto-generated */").virtualFile
        val plain = myFixture.addFileToProject("web/app.ts", "export {}").virtualFile

        assertEquals("in a generated source root", GeneratedFiles.reason(inRoot, project))
        assertTrue(EmberkaiScope.GENERATED.contains(inRoot, project))
        assertTrue(EmberkaiScope.GENERATED.contains(marked, project))
        assertFalse(EmberkaiScope.GENERATED.contains(plain, project))
        assertFalse(EmberkaiScope.GENERATED.contains(root, project))
    }

    private fun decorate(file: PsiFile): PresentationData =
        PresentationData().apply { GeneratedFileDecorator().decorate(PsiFileNode(project, file, ViewSettings.DEFAULT), this) }

    private fun edit(file: PsiFile, text: String) {
        val document = PsiDocumentManager.getInstance(project).getDocument(file)!!
        WriteCommandAction.runWriteCommandAction(project) { document.setText(text) }
    }
}
